-- ─────────────────────────────────────────────────────────────────────────────
-- 4. audit_log_archive table
-- ─────────────────────────────────────────────────────────────────────────────
-- original_log_id is TEXT (not UUID) because:
--   - audit_logs.id is UUID (stored as text representation is compatible)
--   - terminal_audit_log.id is UUID (same)
--   - Future TEXT-PK sources may also be archived here
--   TEXT is the safe common denominator; UUID values are stored canonically.
CREATE TABLE IF NOT EXISTS public.audit_log_archive (
    archive_id      UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    original_log_id TEXT        NOT NULL,   -- UUID or TEXT string from source table's id column
    timestamp       TIMESTAMPTZ NOT NULL,
    module          TEXT        NOT NULL,
    action          TEXT        NOT NULL,
    user_email      TEXT        NOT NULL,
    user_name       TEXT        NULL,
    ip_address      TEXT        NULL,
    location        TEXT        NULL,
    target          TEXT        NULL,
    status          TEXT        NOT NULL,
    metadata        JSONB       NOT NULL DEFAULT '{}'::jsonb,
    tenant_id       UUID        NULL,
    tenant_code     VARCHAR(20) NULL,
    source_origin   TEXT        NOT NULL
                    CHECK (source_origin IN ('AUDIT_LOG', 'TERMINAL_AUDIT', 'DEVICE_AUDIT')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_audit_log_archive_timestamp       ON public.audit_log_archive(timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_audit_log_archive_tenant_id       ON public.audit_log_archive(tenant_id);
CREATE INDEX IF NOT EXISTS idx_audit_log_archive_tenant_code     ON public.audit_log_archive(tenant_code);
CREATE INDEX IF NOT EXISTS idx_audit_log_archive_original_log_id ON public.audit_log_archive(original_log_id);
CREATE INDEX IF NOT EXISTS idx_audit_log_archive_source_origin   ON public.audit_log_archive(source_origin);

