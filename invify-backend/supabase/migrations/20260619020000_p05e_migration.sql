-- ─────────────────────────────────────────────────────────────────────────────
-- SELECT POLICIES
--
-- CAST RATIONALE (derived from live schema inspection and p05b/p05c precedent):
--   users.id       is UUID  → auth.uid() is UUID  → no cast needed
--   users.tenant_id is TEXT → UUID columns need ::text cast on both sides
--   Pattern: users.tenant_id::text = <uuid_column>::text
-- ─────────────────────────────────────────────────────────────────────────────

-- complaints: staff (super_admin, internal_staff, admin_ops, support) can read all
CREATE POLICY "staff_read_all_complaints"
  ON public.complaints FOR SELECT
  USING (
    EXISTS (
      SELECT 1 FROM public.users
      WHERE users.id = auth.uid()
      AND users.role IN ('super_admin', 'internal_staff', 'admin_ops', 'support')
    )
  );

-- complaints: tenant users can read their own tenant's complaints
-- users.tenant_id is TEXT; complaints.tenant_id is UUID → cast both to text
CREATE POLICY "tenant_user_read_own_complaints"
  ON public.complaints FOR SELECT
  USING (
    tenant_id IS NOT NULL
    AND EXISTS (
      SELECT 1 FROM public.users
      WHERE users.id = auth.uid()
      AND users.tenant_id::text = complaints.tenant_id::text
    )
  );

-- apk_vault: staff only (APK management is internal)
CREATE POLICY "staff_read_apk_vault"
  ON public.apk_vault FOR SELECT
  USING (
    EXISTS (
      SELECT 1 FROM public.users
      WHERE users.id = auth.uid()
      AND users.role IN ('super_admin', 'internal_staff', 'admin_ops')
    )
  );

-- apk_deployment_logs: staff only
