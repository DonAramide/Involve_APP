-- ──────────────────────────────────────────────────────────────
-- Column                 | Live DB Type | Evidence
-- ─────────────────────────────────────────────────────────────
-- users.id               | UUID         | auth.uid()-compatible; p05c uses users.id = auth.uid() without cast
-- users.tenant_id        | TEXT         | p05c uses users.tenant_id::text; users_db.json stores as string
-- devices.id             | TEXT         | devices_db.json: "id": "dev-1781561032451" (custom TEXT PK)
-- devices.device_id      | TEXT         | devices_db.json: "device_id": "R52M3012KRB"
-- audit_logs.id          | UUID         | p05c migration: id UUID PRIMARY KEY DEFAULT gen_random_uuid()
-- terminal_audit_log.id  | UUID         | terminal_migration.sql: id UUID PRIMARY KEY DEFAULT gen_random_uuid()
-- tenants.id             | UUID         | Standard Supabase UUID PK on tenants table
--
-- DESIGN DECISIONS:
-- 1. complaints.device_id  → TEXT (matches devices.id TEXT primary key)
-- 2. complaints.tenant_id  → UUID REFERENCES tenants(id) (standard FK)
-- 3. audit_log_archive.original_log_id → TEXT
--      Because source tables differ:
--        - audit_logs.id         is UUID
--        - terminal_audit_log.id is UUID
--      Both are UUIDs, but to support future TEXT sources and avoid a union
--      type problem, we store as TEXT and allow the application to pass
--      either UUID or TEXT values. UUID values will be stored as their
--      canonical string representation.
-- 4. RLS: RESTRICTIVE policies block INSERT + UPDATE + DELETE for all
--      client JWT roles. SELECT is granted only where business rules allow.
--      Backend services use supabaseAdmin (service role) which bypasses RLS.
--
-- CAST PATTERN (consistent with p05b / p05c migrations):
--   users.id = auth.uid()                          ← both UUID, no cast needed
--   users.tenant_id::text = <table>.tenant_id::text ← users.tenant_id is TEXT,
--                                                      UUID column cast to text
-- ─────────────────────────────────────────────────────────────────────────────

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. complaints table
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.complaints (
    id             TEXT        PRIMARY KEY,  -- TKT-XXXXXX format generated by SupportController
    title          TEXT        NOT NULL,
    description    TEXT        NOT NULL,
    category       TEXT        NOT NULL DEFAULT 'general',
    urgency        TEXT        NOT NULL DEFAULT 'normal'
                   CHECK (urgency IN ('normal', 'high', 'critical')),
    status         TEXT        NOT NULL DEFAULT 'pending'
                   CHECK (status IN ('pending', 'in_progress', 'resolved', 'closed')),
    tenant_id      UUID        NULL REFERENCES public.tenants(id) ON DELETE SET NULL,
    tenant_code    VARCHAR(20) NULL,      -- Denormalized; populated from tenants.tenant_code by controller
    tenant_name    TEXT        NULL,      -- Denormalized display only; mutable, do not use for lookups
    -- device_id is TEXT to match public.devices.id which uses custom "dev-XXXXX" TEXT primary key
    device_id      TEXT        NULL,      -- No FK constraint: devices may be deleted; TEXT PK on devices table
    incident_date  TIMESTAMPTZ NULL,
    attachment_url TEXT        NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_complaints_tenant_id   ON public.complaints(tenant_id);
CREATE INDEX IF NOT EXISTS idx_complaints_tenant_code ON public.complaints(tenant_code);
CREATE INDEX IF NOT EXISTS idx_complaints_device_id   ON public.complaints(device_id);
CREATE INDEX IF NOT EXISTS idx_complaints_status      ON public.complaints(status);
CREATE INDEX IF NOT EXISTS idx_complaints_created_at  ON public.complaints(created_at DESC);

-- ─────────────────────────────────────────────────────────────────────────────
-- 2. apk_vault table
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.apk_vault (
    id                      TEXT        PRIMARY KEY,  -- apk-XXXXXX format
    name                    TEXT        NOT NULL,
    package_name            TEXT        NOT NULL,
    version                 TEXT        NOT NULL,
    size                    INTEGER     NOT NULL,
    status                  TEXT        NOT NULL DEFAULT 'READY',
    upload_progress         INTEGER     NOT NULL DEFAULT 100,
    install_count           INTEGER     NOT NULL DEFAULT 0,
    uninstall_count         INTEGER     NOT NULL DEFAULT 0,
