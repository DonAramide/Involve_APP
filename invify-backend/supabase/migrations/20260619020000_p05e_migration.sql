-- audit_log_archive: tenant admins can read their own tenant's archived logs
-- users.tenant_id is TEXT; audit_log_archive.tenant_id is UUID → cast both to text
CREATE POLICY "tenant_admin_read_own_audit_archive"
  ON public.audit_log_archive FOR SELECT
  USING (
    tenant_id IS NOT NULL
    AND EXISTS (
      SELECT 1 FROM public.users
      WHERE users.id = auth.uid()
      AND users.tenant_id::text = audit_log_archive.tenant_id::text
      AND users.role IN ('owner', 'admin', 'tenant_admin')
    )
  );
